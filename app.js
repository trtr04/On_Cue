const STORAGE_KEY = "on-cue-demo-recordings";
const seedRecordings = [{ id: "family-dinner", title: COPY.seedTitle, meta: COPY.seedMeta }];

function applyLocalization() {
  document.title = I18N.title;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = I18N[node.dataset.i18n] || "";
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = I18N[node.dataset.i18nHtml] || "";
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", I18N[node.dataset.i18nAriaLabel] || "");
  });
  document.querySelectorAll("[data-i18n-value]").forEach((node) => {
    node.value = I18N[node.dataset.i18nValue] || "";
  });
}

applyLocalization();

const phone = document.querySelector(".phone");
const screens = [...document.querySelectorAll("[data-screen]")];
const guides = [...document.querySelectorAll("[data-guide]")];
const savedList = document.querySelector("#saved-list");
const savedSection = document.querySelector("#saved-recordings");
const timerElement = document.querySelector("#timer");
const toast = document.querySelector("#toast");

let recordings = loadRecordings();
let elapsed = 0;
let timerId = null;
let toastId = null;

function loadRecordings() {
  try {
    const value = JSON.parse(localStorage.getItem(STORAGE_KEY));
    return Array.isArray(value) ? value : seedRecordings;
  } catch {
    return seedRecordings;
  }
}

function persistRecordings() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(recordings));
}

function waveform() {
  const heights = [12, 24, 18, 33, 27, 16, 30, 14, 21, 10, 26, 18, 31, 16];
  return heights
    .map((height, index) => `<i class="${[3, 4, 10].includes(index) ? "hot" : ""}" style="--h:${height}px"></i>`)
    .join("");
}

function renderRecordings() {
  savedList.innerHTML = recordings
    .map(
      (recording) => `
        <article class="saved-card">
          <strong>${recording.title}</strong>
          <div class="meta">${recording.meta}</div>
          <div class="saved-bottom">
            <div class="mini-wave" aria-hidden="true">${waveform()}</div>
            <button class="button primary" data-action="analyze">${COPY.analyzeNow}</button>
          </div>
        </article>
      `,
    )
    .join("");
}

function formatTimer(seconds) {
  const minutes = String(Math.floor(seconds / 60)).padStart(2, "0");
  const remainder = String(seconds % 60).padStart(2, "0");
  return `${minutes}:${remainder}`;
}

function startTimer() {
  clearInterval(timerId);
  elapsed = 0;
  timerElement.textContent = "00:00";
  timerId = setInterval(() => {
    elapsed += 1;
    timerElement.textContent = formatTimer(elapsed);
  }, 1000);
}

function stopTimer() {
  clearInterval(timerId);
  timerId = null;
}

function showToast(message) {
  clearTimeout(toastId);
  toast.textContent = message;
  toast.classList.add("show");
  toastId = setTimeout(() => toast.classList.remove("show"), 2200);
}

function showScreen(id, { scrollToSaved = false } = {}) {
  screens.forEach((screen) => {
    const active = screen.dataset.screen === id;
    screen.classList.toggle("active", active);
    screen.setAttribute("aria-hidden", String(!active));
    if (active && !scrollToSaved) {
      screen.querySelector(".scroll-page")?.scrollTo({ top: 0 });
      screen.scrollTop = 0;
    }
  });
  guides.forEach((guide) => guide.classList.toggle("active", guide.dataset.guide === id));
  phone.classList.toggle("no-nav", id !== "home");
  if (id === "recording") startTimer();
  else stopTimer();
  if (id === "home" && scrollToSaved) {
    requestAnimationFrame(() => savedSection.scrollIntoView({ behavior: "smooth", block: "start" }));
  }
}

function addRecording(recording) {
  recordings = [recording, ...recordings.filter((item) => item.id !== recording.id)];
  persistRecordings();
  renderRecordings();
}

document.addEventListener("click", (event) => {
  const control = event.target.closest("[data-action]");
  if (!control) return;
  switch (control.dataset.action) {
    case "record":
      showScreen("recording");
      break;
    case "home":
      showScreen("home");
      break;
    case "save-current":
      addRecording({ id: "mentor-plan", title: COPY.savedTitle, meta: COPY.savedMeta });
      showToast(COPY.toastSaved);
      showScreen("home", { scrollToSaved: true });
      break;
    case "save-recording":
      addRecording({
        id: `live-${Date.now()}`,
        title: COPY.liveTitle,
        meta: `${COPY.justNow} \u00b7 ${formatTimer(Math.max(elapsed, 18))} \u00b7 ${COPY.stored}`,
      });
      showToast(COPY.toastLiveSaved);
      showScreen("home", { scrollToSaved: true });
      break;
    case "analyze":
      showScreen("analysis");
      break;
    case "mark":
      control.textContent = `${COPY.marked} ${formatTimer(elapsed)}`;
      showToast(COPY.toastMarked);
      break;
    case "replay":
      showToast(COPY.toastReplay);
      break;
    case "noop":
      showToast(COPY.toastNoop);
      break;
  }
});

document.querySelector("#coach-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const input = document.querySelector("#coach-input");
  const response = document.querySelector("#ai-response");
  if (!input.value.trim()) return;
  response.hidden = false;
  response.textContent = COPY.aiResponse;
  input.value = "";
  requestAnimationFrame(() => response.scrollIntoView({ behavior: "smooth", block: "center" }));
});

renderRecordings();
showScreen("home");
